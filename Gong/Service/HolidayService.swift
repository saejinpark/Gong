    /// 공휴일 데이터가 준비된 마지막 연도. 이후 연도는 일요일만 공휴일로 표시됨.
    static let lastSupportedYear = 2028

    private static let formatter: DateFormatter = {
        let f = DateFormatter()
        f.dateFormat = "yyyy-MM-dd"
        f.locale = Locale(identifier: "ko_KR")
        f.calendar = Calendar(identifier: .gregorian)
        return f
    }()

    private static func key(for date: Date) -> String {
        formatter.string(from: date)
    }

    /// 공휴일 이름 (일요일은 nil — 날짜 색으로만 표시)
    static func holidayName(for date: Date) -> String? {
        holidays[key(for: date)]
    }

    /// 날짜 → DayType 자동 판별
    static func dayType(for date: Date) -> DayType {
        if holidays[key(for: date)] != nil { return .holiday }

        let weekday = Calendar.current.component(.weekday, from: date)
        switch weekday {
        case 1: return .holiday   // 일요일
        case 7: return .saturday  // 토요일
        default: return .weekday
        }
    }

    static func isHoliday(_ date: Date) -> Bool {
        dayType(for: date) == .holiday
    }

    /// 해당 연도의 공휴일 데이터가 있는지
    static func hasData(forYear year: Int) -> Bool {
        year <= lastSupportedYear && year >= 2025
    }
